/*
============================================================
Query 43 : Identify High-Risk Customers
------------------------------------------------------------
Business Question:
Which customers are most likely to churn based on
known business rules?

Objective:
Flag customers who satisfy multiple high-risk conditions.
-------------------------------------------------------------
A customer is considered High Risk if:

Month-to-month contract ✅
Fiber Optic Internet ✅
Electronic Check payment ✅

Why these three?

Because our SQL analysis already showed:

✔ Highest churn contract

✔ Highest churn internet service

✔ Highest churn payment method
============================================================
