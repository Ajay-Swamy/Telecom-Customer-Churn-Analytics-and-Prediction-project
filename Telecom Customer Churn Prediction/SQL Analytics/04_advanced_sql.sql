/*
============================================================
Query 39 : Top Customer in Each Contract Type
------------------------------------------------------------
Business Question:
Who is the highest revenue customer within each contract type?

Objective:
Rank customers separately inside each contract category.

SQL Concepts:
ROW_NUMBER(), PARTITION BY
============================================================
*/

WITH ranked_customers AS (

    SELECT

        customerID,

        Contract,

        TotalCharges::NUMERIC AS total_charges,

        ROW_NUMBER() OVER(

            PARTITION BY Contract
            ORDER BY TotalCharges::NUMERIC DESC

        ) AS contract_rank

    FROM telecom.telecom_churn

    WHERE TotalCharges IS NOT NULL

)

SELECT *

FROM ranked_customers

WHERE contract_rank = 1;


/*
============================================================
Query 40 : Highest Revenue Customer by Payment Method

Business Question:

Which customer contributes the highest revenue for each payment method?
============================================================
*/

WITH ranked_customers AS (

    SELECT

        customerID,

        PaymentMethod,

        TotalCharges::NUMERIC AS total_charges,

        ROW_NUMBER() OVER(

            PARTITION BY PaymentMethod
            ORDER BY TotalCharges::NUMERIC DESC

        ) AS payment_rank

    FROM telecom.telecom_churn

    WHERE TotalCharges IS NOT NULL

)

SELECT *

FROM ranked_customers

WHERE payment_rank = 1;


/*
============================================================
Query 41 : Customer Revenue Quartiles
------------------------------------------------------------
Business Question:
Can customers be divided into revenue quartiles?

Objective:
Split customers into four equal-sized groups based on
Total Charges.

SQL Concepts:
NTILE(), OVER(), ORDER BY
============================================================
*/

SELECT

    customerID,

    TotalCharges::NUMERIC AS total_charges,

    NTILE(4) OVER(

        ORDER BY TotalCharges::NUMERIC DESC

    ) AS revenue_quartile

FROM telecom.telecom_churn

WHERE TotalCharges IS NOT NULL;


WITH quartiles AS (
    SELECT
        NTILE(4) OVER (ORDER BY TotalCharges::NUMERIC DESC) AS revenue_quartile
    FROM telecom.telecom_churn
    WHERE TotalCharges IS NOT NULL
)

SELECT
    revenue_quartile,
    COUNT(*) AS customers
FROM quartiles
GROUP BY revenue_quartile
ORDER BY revenue_quartile;

/*
============================================================
Query 42 : Compare Customer Revenue with Previous Customer
------------------------------------------------------------
Business Question:
