/*
============================================================
Query 31 : Customer Value Segmentation
------------------------------------------------------------
Business Question:
Can customers be segmented based on their lifetime revenue?

Objective:
Categorize customers into Low, Medium and High Value
using Total Charges.
============================================================
*/
with customer_segments as (
SELECT
    customerID,
    TotalCharges::NUMERIC AS total_charges,

    CASE
        WHEN TotalCharges::NUMERIC < 1000
            THEN 'Low Value'

        WHEN TotalCharges::NUMERIC BETWEEN 1000 AND 3000
            THEN 'Medium Value'

        ELSE 'High Value'
    END AS customer_segment

FROM telecom.telecom_churn
WHERE TotalCharges IS NOT NULL
)



/*
============================================================
Query 32 : Number of Customers in Each Segment
============================================================
*/

SELECT
	customer_segment,
	COUNT(*) AS customers
FROM customer_segments
GROUP BY customer_segment
ORDER BY customers DESC;



/*
============================================================
Query 33 : Revenue Contribution by Customer Segment
------------------------------------------------------------
Business Question:
Which customer segment contributes the most revenue?

Objective:
Measure the total and average revenue generated by
Low, Medium, and High Value customers.

SQL Concepts:
CTE, CASE, SUM, AVG, GROUP BY
============================================================
*/

WITH customer_segments AS (

    SELECT
        customerID,
        TotalCharges::NUMERIC AS total_charges,

        CASE
            WHEN TotalCharges::NUMERIC < 1000 THEN 'Low Value'
            WHEN TotalCharges::NUMERIC BETWEEN 1000 AND 3000 THEN 'Medium Value'
            ELSE 'High Value'
        END AS customer_segment

    FROM telecom.telecom_churn

    WHERE TotalCharges IS NOT NULL

)

SELECT

    customer_segment,

    COUNT(*) AS total_customers,

    ROUND(SUM(total_charges),2) AS total_revenue,

    ROUND(AVG(total_charges),2) AS average_revenue

FROM customer_segments

GROUP BY customer_segment

ORDER BY total_revenue DESC;



/*
============================================================
Query 34 : Average Monthly Charges by Customer Segment
------------------------------------------------------------
Business Question:
Do High Value customers pay higher monthly charges?

Objective:
Compare the average monthly charges across customer segments.

SQL Concepts:
CTE, CASE, AVG, GROUP BY
============================================================
