/*
============================================================
Query 47 : Most Churn-Prone Customer Segments
------------------------------------------------------------
Business Question:
Which combination of Contract and Internet Service
has the highest churn rate?

Objective:
Calculate churn rate for each Contract × Internet Service
combination.

SQL Concepts:
GROUP BY, FILTER
============================================================
*/

SELECT

    Contract,

    InternetService,

    COUNT(*) AS Customers,

    COUNT(*) FILTER(

        WHERE Churn='Yes'

    ) AS Churned,

    ROUND(

        COUNT(*) FILTER(

            WHERE Churn='Yes'

        )*100.0

        /

        COUNT(*),

        2

    ) AS Churn_Rate

FROM telecom.telecom_churn

GROUP BY

Contract,

InternetService

ORDER BY

Churn_Rate DESC;


