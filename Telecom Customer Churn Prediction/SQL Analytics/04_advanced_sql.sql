Query 36 : Rank Customers using ROW_NUMBER()
------------------------------------------------------------
Business Question:
Who are the highest revenue customers?

Objective:
Assign a unique rank to every customer based on
Total Charges.

SQL Concepts:
ROW_NUMBER(), OVER(), ORDER BY
============================================================
